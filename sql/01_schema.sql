CREATE TABLE public.clients (
    client_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom text NOT NULL,
    prenom text NOT NULL,
    email text NOT NULL UNIQUE,
    date_inscription timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.utilisateurs (
    user_id uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    client_id bigint UNIQUE REFERENCES public.clients (client_id) ON DELETE SET NULL,
    date_creation timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.utilisateurs ENABLE ROW LEVEL SECURITY;

CREATE POLICY utilisateurs_select_own_profile
    ON public.utilisateurs
    FOR SELECT
    TO authenticated
    USING (user_id = (SELECT auth.uid()));

GRANT SELECT ON public.utilisateurs TO authenticated;

CREATE TABLE public.comptes_especes (
    compte_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES public.clients (client_id) ON DELETE RESTRICT,
    solde numeric(18, 2) NOT NULL DEFAULT 0 CHECK (solde >= 0),
    devise char(3) NOT NULL CHECK (devise ~ '^[A-Z]{3}$'),
    date_ouverture timestamptz NOT NULL DEFAULT now(),
    UNIQUE (compte_id, client_id)
);

CREATE TABLE public.titres (
    titre_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbole text NOT NULL UNIQUE,
    nom text NOT NULL,
    secteur text,
    devise char(3) NOT NULL CHECK (devise ~ '^[A-Z]{3}$'),
    cours_actuel numeric(18, 4) NOT NULL CHECK (cours_actuel >= 0)
);

CREATE TABLE public.portefeuilles_positions (
    position_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES public.clients (client_id) ON DELETE RESTRICT,
    titre_id bigint NOT NULL REFERENCES public.titres (titre_id) ON DELETE RESTRICT,
    quantite numeric(20, 8) NOT NULL CHECK (quantite > 0),
    prix_moyen_achat numeric(18, 4) NOT NULL CHECK (prix_moyen_achat >= 0),
    date_premier_achat timestamptz NOT NULL DEFAULT now(),
    UNIQUE (client_id, titre_id)
);

CREATE TABLE public.transactions (
    transaction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES public.clients (client_id) ON DELETE RESTRICT,
    compte_id bigint NOT NULL,
    titre_id bigint NOT NULL REFERENCES public.titres (titre_id) ON DELETE RESTRICT,
    type text NOT NULL CHECK (type IN ('ACHAT', 'VENTE')),
    quantite numeric(20, 8) NOT NULL CHECK (quantite > 0),
    prix_unitaire numeric(18, 4) NOT NULL CHECK (prix_unitaire > 0),
    date_transaction timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (compte_id, client_id)
        REFERENCES public.comptes_especes (compte_id, client_id)
        ON DELETE RESTRICT
);
